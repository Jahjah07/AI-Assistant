  await assert.rejects(run.toolForChat('check my emails', signal), /No check history was reset/);
  assert.equal(await readFile('storage/gmail-checks.json', 'utf8'), 'broken json');
  await writeFile('storage/gmail-checks.json', beforeReply);
  process.env.VOICE_SERVICE_SECRET = 'changed-key-'.repeat(4);
  assert.throws(() => store.toolSecret(tools[0]), /Re-enter/);
