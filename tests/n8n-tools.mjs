  assert.equal(nextDay.input.query, firstCheck.input.query, 'Unseen older pages survive until Tuesday');
  assert.equal(nextDay.input.pageToken, 'older-page');
  await nextDay.complete({ nextPageToken: '' });
  const sinceMonday = await beginGmailCheck(tools[0], fallback, signal, undefined, tuesdayNoon);
