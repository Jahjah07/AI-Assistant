  await assert.rejects(run.runTool('gmail', {}, 'read', AbortSignal.timeout(5000)), /more than 8 MiB/);
  const { UpstreamTimeoutError } = await load('app/api/_limits');
  globalThis.fetch = async () => { throw new UpstreamTimeoutError(); };
  await assert.rejects(run.runTool('gmail', {}, 'read', AbortSignal.timeout(5000)), /timed out.*workflow may still be running/i);
  globalThis.fetch = async () => Response.json(Array.from({ length: 200 }, () => ({ preview: 'long preview '.repeat(20) })));
  assert.match((await run.toolForChat('find emails about updates', AbortSignal.timeout(5000))).context, /incomplete excerpt/);
