  await assert.rejects(run.runTool('gmail', {}, 'read', aborted.signal), /abort/i);
  const { beginGmailCheck } = await load('app/api/n8n-tools/gmail-checks');
  const mondayNoon = new Date('2026-10-12T12:00:00+08:00'), tuesdayNoon = new Date('2026-10-13T12:00:00+08:00');
  const fallback = `is:unread after:${monday}`;
  const signal = new AbortController().signal;
  const firstCheck = await beginGmailCheck(tools[0], fallback, signal, undefined, mondayNoon);
  assert.equal(firstCheck.input.query, `is:unread after:${monday - 1} before:${mondayNoon.getTime() / 1000}`);
  await assert.rejects(beginGmailCheck(tools[0], fallback, signal, undefined, mondayNoon), /already in progress/);
  await firstCheck.complete({ nextPageToken: 'older-page' });
