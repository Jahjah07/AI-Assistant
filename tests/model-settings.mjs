import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';

const root = process.cwd(), originalFetch = globalThis.fetch;
const temporary = await mkdtemp(path.join(tmpdir(), 'jimmy-models-'));
try {
  for (const source of ['app/api/_security', 'app/api/_limits', 'app/api/model-settings/settings', 'app/api/model-settings/route']) {
    const output = ts.transpileModule(await readFile(`${source}.ts`, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace(/from "(\.[^"]+)"/g, 'from "$1.mjs"');
    await mkdir(path.dirname(path.join(temporary, source)), { recursive: true }); await writeFile(path.join(temporary, `${source}.mjs`), output);
  }
  process.chdir(temporary);
  process.env.JIMMY_AUTH_USERNAME = 'test'; process.env.JIMMY_AUTH_PASSWORD = 'test-password'; process.env.JIMMY_ALLOWED_HOSTS = 'localhost'; process.env.VOICE_SERVICE_SECRET = 'test-secret';
  const { GET, POST } = await import(pathToFileURL(path.join(temporary, 'app/api/model-settings/route.mjs')));
  const request = (body, auth = true) => new Request('http://localhost/api/model-settings', { method: body ? 'POST' : 'GET', headers: { host: 'localhost', ...(auth ? { authorization: `Basic ${Buffer.from('test:test-password').toString('base64')}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await GET(request(null, false))).status, 401);
  const calls = [];
  let failed = false;
  const defaultModel = process.env.OLLAMA_MODEL || 'qwen3:4b-instruct';
  let embedding = false, cloud = false, missingOld = false;
  globalThis.fetch = async (url, options) => {
    calls.push({ url: String(url), options });
    if (String(url).endsWith('/tags')) return Response.json({ models: [{ name: defaultModel, size: 2e9 }, { name: 'friend:14b', size: 9e9 }, { name: 'cloud-model:cloud', size: 1 }] });
    if (String(url).endsWith('/show')) return Response.json({ capabilities: [embedding ? 'embedding' : 'completion'], ...(cloud ? { remote_host: 'https://ollama.com' } : {}) });
    if (missingOld && JSON.parse(options.body || '{}').keep_alive === 0) return Response.json({}, { status: 404 });
    return Response.json({}, { status: failed ? 503 : 200 });
  };
  const initial = await (await GET(request())).json();
  assert.equal(initial.keepLoaded, false);
  assert.equal(initial.model, defaultModel);
  assert.equal(initial.models.length, 2, 'Cloud tags do not appear in the local picker');
  assert.equal((await POST(request({ keepLoaded: 'true' }))).status, 400);
  assert.equal((await POST(request({ keepLoaded: true }))).status, 200);
  assert.equal((await (await GET(request())).json()).keepLoaded, true);
  assert.ok(calls.some(call => call.url.endsWith('/warm') && call.options.headers['X-Voice-Service-Secret'] === 'test-secret'));
  assert.equal(JSON.parse(calls.find(call => call.url.endsWith('/generate')).options.body).keep_alive, -1);
  calls.length = 0;
  assert.equal((await POST(request({ keepLoaded: false }))).status, 200);
  assert.equal(JSON.parse(calls[0].options.body).keep_alive, '30m');
  assert.equal((await (await GET(request())).json()).keepLoaded, false);
  failed = true;
  assert.equal((await POST(request({ keepLoaded: true }))).status, 503);
  assert.equal((await (await GET(request())).json()).keepLoaded, false, 'Failed warm-up must not save an enabled preference');
  failed = false;
  assert.equal((await POST(request({ model: 'not-installed' }))).status, 400);
  embedding = true;
  assert.equal((await POST(request({ model: 'friend:14b' }))).status, 400);
  embedding = false; cloud = true;
  assert.equal((await POST(request({ model: 'friend:14b' }))).status, 400);
  cloud = false; missingOld = true;
  assert.equal((await POST(request({ model: 'friend:14b' }))).status, 200, 'A missing previous model does not prevent choosing an installed replacement');
  missingOld = false;
  const settings = await import(pathToFileURL(path.join(temporary, 'app/api/model-settings/settings.mjs')));
  assert.equal(await settings.chatModel(), 'friend:14b');
  assert.equal(await settings.keepModelsLoaded(), false);
  calls.length = 0;
  assert.equal((await POST(request({ keepLoaded: true }))).status, 200);
  assert.equal(JSON.parse(calls.find(call => call.url.endsWith('/generate')).options.body).model, 'friend:14b');
  calls.length = 0;
  assert.equal((await POST(request({ model: defaultModel }))).status, 200);
  const generated = calls.filter(call => call.url.endsWith('/generate')).map(call => JSON.parse(call.options.body));
  assert.deepEqual(generated.map(body => [body.model, body.keep_alive]), [['friend:14b', 0], [defaultModel, -1]], 'Switching a pinned model unloads the old one before warming the new one');
  assert.equal(await settings.keepModelsLoaded(), true);
  failed = true; missingOld = true;
  assert.equal((await POST(request({ model: 'friend:14b' }))).status, 503);
  assert.equal(await settings.chatModel(), defaultModel, 'Failed switching preserves the saved model');
  assert.equal(await settings.keepModelsLoaded(), true);
  assert.equal((await POST(request({ model: 14 }))).status, 400);
  globalThis.fetch = async () => { throw new Error('Offline'); };
  const offline = await (await GET(request())).json();
  assert.equal(offline.model, defaultModel);
  assert.ok(offline.modelsError);
  await settings.saveKeepModelsLoaded(false);
  assert.equal(await settings.chatModel(), defaultModel, 'Legacy keep-loaded writes preserve the selected model');
  await writeFile('storage/model-settings.json', '{broken');
  assert.equal((await GET(request())).status, 503);
  await assert.rejects(settings.saveKeepModelsLoaded(true));
  assert.equal(await readFile('storage/model-settings.json', 'utf8'), '{broken', 'Unreadable settings are never overwritten');
  console.log('Passed: installed model discovery, completion/cloud validation, persistent selection, safe switching/unloading, pinning, failed warm-up rollback, offline lists and corrupt-file protection.');
} finally { globalThis.fetch = originalFetch; process.chdir(root); await rm(temporary, { recursive: true, force: true }); }
