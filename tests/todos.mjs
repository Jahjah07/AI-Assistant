import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import ts from 'typescript';
const cwd = process.cwd(), temporary = await mkdtemp(path.join(tmpdir(), 'jimmy-todos-'));
try {
  for (const source of ['app/lib/todos', 'app/lib/voice-commands', 'app/api/_security', 'app/api/_limits', 'app/api/todos/store', 'app/api/todos/route']) {
    const compiled = ts.transpileModule(await readFile(source + '.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText.replace(/from "(\.[^"]+)"/g, 'from "$1.mjs"');
    await mkdir(path.dirname(path.join(temporary, source)), { recursive: true }); await writeFile(path.join(temporary, source + '.mjs'), compiled);
  }
  process.chdir(temporary);
  const load = source => import(pathToFileURL(path.join(temporary, source + '.mjs')));
  const { parseTodoCommand, todoDate, todoTime, formatTodoTime, splitTodoTime } = await load('app/lib/todos');
  const { parseVoiceCommand } = await load('app/lib/voice-commands');
  assert.equal(todoDate('today', new Date('2026-10-15T16:01:00Z')), '2026-10-16');
  assert.equal(todoDate('tomorrow', new Date('2026-12-31T16:01:00Z')), '2027-01-02');
  assert.equal(todoDate('tomorrow', new Date('2028-02-28T00:01:00Z')), '2028-02-29');
  assert.throws(() => todoDate('2026-02-30'));
  for (const [input, expected] of [['3 PM', '15:00'], ['3:30 p.m.', '15:30'], ['12 AM', '00:00'], ['12 PM', '12:00'], ['noon', '12:00'], ['midnight', '00:00'], ['03:00', '03:00'], ['23:59', '23:59']]) assert.equal(todoTime(input), expected, input);
  for (const input of ['3', '3:30', '13 PM', '0 AM', '24:00', '12:60']) assert.throws(() => todoTime(input), input);
  assert.equal(formatTodoTime('00:00'), '12 AM'); assert.equal(formatTodoTime('15:30'), '3:30 PM');
  assert.deepEqual(splitTodoTime('Work at home'), { text: 'Work at home' });
  const timed = parseTodoCommand('Add finish slides to my to-do list for tomorrow at 3 PM');
  assert.equal(timed.time, '15:00'); assert.equal(timed.day, 'tomorrow'); assert.equal(timed.text, 'finish slides');
  assert.equal(parseTodoCommand('Add finish slides at 3:30 PM to my to-do list for tomorrow').time, '15:30');
  assert.equal(parseTodoCommand('Set task 1 to 4:30 PM for tomorrow').time, '16:30');
  assert.equal(parseTodoCommand("Change task 2's time to noon").time, '12:00');
  assert.match(parseTodoCommand('Add finish slides to my todo list at 3').timeError, /AM or PM/);
  assert.equal(parseTodoCommand('Add this task to my todo list for tomorrow at 3 PM').time, '15:00');
  assert.equal(parseVoiceCommand('Jimmy, create me a todo list for tommorow.').day, 'tomorrow');
  for (const text of ["What's in my to-do list?", 'Do I have something to do today?', 'Show my todo list', 'What do I need to do tomorrow?']) assert.equal(parseTodoCommand(text)?.action, 'list', text);
  assert.equal(parseTodoCommand('Add finish my slides to my to-do list for tomorrow').text, 'finish my slides');
  assert.equal(parseTodoCommand('Add finish my slides for tomorrow to my to-do list').day, 'tomorrow');
  assert.equal(parseTodoCommand('Add this task in my todo list').text, undefined);
  assert.equal(parseTodoCommand('Add to my to-do list: discuss tomorrow with the team').day, undefined, 'A date inside the task is not a scheduling instruction');
  assert.equal(parseTodoCommand('Create a todo list: plan tomorrow').day, undefined);
  assert.equal(parseTodoCommand('Mark task 2 done for tomorrow').number, 2);
  assert.equal(parseTodoCommand('Mark task 2 not done').done, false);
  for (const text of ['Hide todo list', 'Jimmy, close my to-do list.', 'Please dismiss the task list']) assert.equal(parseVoiceCommand(text)?.action, 'hide', text);
  for (const text of ['Do not add work to my todo list', 'Explain how to create a todo list', 'Create a workflow that reads a task list', 'Add a label to my Gmail messages']) assert.equal(parseTodoCommand(text), null, text);
  const store = await load('app/api/todos/store');
  const day = '2026-10-16';
  assert.equal((await store.getTodos(day)).exists, false);
  assert.equal((await store.changeTodos({ action: 'create', day })).exists, true);
  await store.changeTodos({ action: 'add', day, text: 'Finish the presentation;Email the team' });
  await store.changeTodos({ action: 'create', day });
  assert.equal((await store.getTodos(day)).tasks.length, 2, 'Creating an existing list preserves tasks');
  await Promise.all(['Buy groceries', 'Review portfolio'].map(text => store.changeTodos({ action: 'add', day, text })));
  assert.equal((await store.getTodos(day)).tasks.length, 4, 'Concurrent adds preserve both tasks');
  await store.changeTodos({ action: 'done', day, number: 1, done: true });
  const view = await store.getTodos(day);
  assert.ok(view.tasks[0].done); assert.match(view.reply, /3 unfinished/); assert.match(view.reply, /2\. Email the team/);
  const restarted = await import(pathToFileURL(path.join(temporary, 'app/api/todos/store.mjs')).href + '?restart');
  assert.equal((await restarted.getTodos(day)).tasks.length, 4);
  for (const input of [{ action: 'add', day, text: '' }, { action: 'add', day, text: ';' }, { action: 'add', day, text: 'x'.repeat(501) }, { action: 'add', day: '2026-02-30', text: 'bad date' }, { action: 'done', day, number: -1, done: true }]) await assert.rejects(store.changeTodos(input));
  await store.changeTodos({ action: 'remove', day, id: view.tasks[3].id }); assert.equal((await store.getTodos(day)).tasks.length, 3);
  process.env.JIMMY_AUTH_USERNAME = 'test'; process.env.JIMMY_AUTH_PASSWORD = 'test-pass'; process.env.JIMMY_ALLOWED_HOSTS = 'localhost';
  const api = await load('app/api/todos/route');
  const request = (body, auth = true) => new Request(`http://localhost/api/todos?day=${day}`, { method: body ? 'POST' : 'GET', headers: { host: 'localhost', ...(auth ? { authorization: 'Basic ' + Buffer.from('test:test-pass').toString('base64') } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await api.GET(request(null, false))).status, 401);
  assert.equal((await api.POST(request({ action: 'add', day, text: 'No' }, false))).status, 401);
  assert.equal((await (await api.GET(request())).json()).tasks.length, 3);
  assert.equal((await api.POST(request({ action: 'add', day, text: 'API task' }))).status, 200);
  const timedDay = '2026-10-17';
  await store.changeTodos({ action: 'add', day: timedDay, text: 'Prepare slides at 3 PM;Call the team at 4:30 PM;Review notes', time: '09:00' });
  const scheduled = await store.getTodos(timedDay);
  assert.deepEqual(scheduled.tasks.map(task => task.time), ['15:00', '16:30', '09:00']);
  assert.equal((await restarted.getTodos(timedDay)).tasks[1].time, '16:30', 'Task times survive a storage module restart');
  assert.match(scheduled.reply, /At 3 PM: Prepare slides/);
  assert.equal((await store.getTodos(day)).tasks[0].time, undefined, 'Existing untimed tasks are preserved');
  await store.changeTodos({ action: 'time', day: timedDay, number: 1, time: '18:00' });
  assert.equal((await store.getTodos(timedDay)).tasks[0].time, '18:00');
  await store.changeTodos({ action: 'time', day: timedDay, number: 1, time: '' });
  assert.equal((await store.getTodos(timedDay)).tasks[0].time, undefined);
  await assert.rejects(store.changeTodos({ action: 'add', day: timedDay, text: 'Invalid task', time: '3' }), /AM or PM/);
  await assert.rejects(store.changeTodos({ action: 'add', day: timedDay, text: 'Valid at 3 PM;Invalid at 99 PM' }), /AM or PM/);
  assert.equal((await store.getTodos(timedDay)).tasks.length, 3, 'An invalid batch does not partially save tasks');
  await writeFile('storage/todos.json', '{broken', 'utf8');
  await assert.rejects(store.changeTodos({ action: 'add', day, text: 'Must not overwrite' }), /left unchanged/);
  assert.equal(await readFile('storage/todos.json', 'utf8'), '{broken');
  console.log('Passed: to-do commands, Manila midnight/year/leap-day dates, task-title preservation, persistence, safe creation, concurrent adds, completion, removal, authentication and corrupt-store preservation.');
} finally { process.chdir(cwd); await rm(temporary, { recursive: true, force: true }); }
